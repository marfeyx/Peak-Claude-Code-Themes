# marbles, and the marbles themselves. Sourced by the kugel themes after
# core.sh; it draws nothing on its own.
#
# Everything is painted on a framebuffer of square sub-pixels, one terminal
# column wide and half a terminal row tall, then packed two to a cell as
# U+2580 / U+2584 / U+2588 with a per-cell foreground and background. A marble
# of diameter N therefore covers N columns and N/2 rows and stays round.
#
# The tiles and jar layers below the generated marker are produced by
# vendor/kugel/generate_sprites.py; regenerate them there, never by hand.
#
# Public entry points:
#
#   kugel_jar FILL OVERFLOW [VARIANT] [MAX_COLUMNS] [FAILED] [FRESH]
#       Renders the jar holding FILL marbles (0..65) with OVERFLOW more piled
#       on the bench beside it. VARIANT is FULL (7 rows) or COMPACT (4 rows).
#       FAILED marbles are drawn dull, spread evenly. FRESH=1 brightens the
#       newest marble. Rows land in KUGEL_ROWS, their cell widths in
#       KUGEL_WIDTHS, the number of marbles drawn in the jar in KUGEL_JAR_BEADS
#       and on the bench in KUGEL_SPILL_SHOWN. The jar shows 6 (FULL) or 3
#       (COMPACT) marbles; FILL maps onto them proportionally, so one marble
#       shows one bead and 65 shows a jar filled to the neck.
#
#   kugel_marble SIZE PHASE [VARIANT] [SHADE]
#       Renders one marble of SIZE sub-pixels (4 5 6 8 10 12 16) shifted
#       right by PHASE quarter sub-pixels (0..3). VARIANT is ruby or dull.
#       Rows land in KUGEL_ROWS and KUGEL_WIDTHS.
#
#   kugel_canvas, kugel_put, kugel_blit_marble, kugel_blit_marble_at,
#   kugel_draw_jar, kugel_compose
#       The same pieces, for a theme that composes its own scene (a track, a
#       chute, a marble in flight) in one framebuffer.

