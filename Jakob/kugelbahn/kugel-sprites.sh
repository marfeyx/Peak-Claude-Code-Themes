# Creates an empty framebuffer of WIDTH x HEIGHT sub-pixels in KUGEL_PX.
kugel_canvas() {
  local i total=$(( $1 * $2 ))
  KUGEL_CW=$1
  KUGEL_CH=$2
  KUGEL_PX=()
  for (( i = 0; i < total; i++ )); do KUGEL_PX[i]=.; done
}

# Paints one sub-pixel at X Y with tone code TONE, ignoring anything off-canvas.
kugel_put() {
  (( $1 < 0 || $1 >= KUGEL_CW || $2 < 0 || $2 >= KUGEL_CH )) || KUGEL_PX[$2 * KUGEL_CW + $1]="$3"
}

_kugel_size() {
  local size best=${KUGEL_SIZES[0]}
  for size in "${KUGEL_SIZES[@]}"; do (( size <= $1 )) && best=$size; done
  KUGEL_SIZE=$best
}

# Blits a marble tile of SIZE at sub-pixel X Y and PHASE (0..3), in VARIANT
# (ruby or dull), darkened by SHADE ramp steps (negative brightens).
kugel_blit_marble() {
  local x0=$1 y0=$2 phase=$(( ${4:-0} & 3 )) set=$KUGEL_RUBY shade=${6:-0} iy ix row index c
  _kugel_size "$3"
  [ "${5:-ruby}" = dull ] && set=$KUGEL_DULL
  local -n tile="KUGEL_TILE_${KUGEL_SIZE}_${phase}"
  for (( iy = 0; iy < ${#tile[@]}; iy++ )); do
    row=${tile[iy]}
    for (( ix = 0; ix < ${#row}; ix++ )); do
      c=${row:ix:1}
      [ "$c" = . ] && continue
      index=$(( c + shade ))
      (( c == 0 && shade > 0 )) && index=0
      (( index < 0 )) && index=0
      (( index > 8 )) && index=8
      kugel_put $(( x0 + ix )) $(( y0 + iy )) "${set:index:1}"
    done
  done
}

# Blits a marble whose left edge sits at XQ quarter sub-pixels, for rolling.
kugel_blit_marble_at() {
  local quarter=$1
  (( quarter < 0 )) && quarter=$(( quarter - 3 ))
  kugel_blit_marble $(( quarter / 4 )) "$2" "$3" $(( $1 & 3 )) "${4:-ruby}" "${5:-0}"
}

_kugel_lighten() {
  local tone=${KUGEL_PX[$1]} steps=$2 index
  case "$tone" in
    v) [ "$steps" -ge 2 ] && KUGEL_PX[$1]=t || KUGEL_PX[$1]=u ;;
    u) KUGEL_PX[$1]=t ;;
    [A-I])
      index=${KUGEL_RUBY%%"$tone"*}
      index=$(( ${#index} - steps ))
      (( index < 0 )) && index=0
      KUGEL_PX[$1]=${KUGEL_RUBY:index:1} ;;
    [a-i])
      index=${KUGEL_DULL%%"$tone"*}
      index=$(( ${#index} - steps ))
      (( index < 0 )) && index=0
      KUGEL_PX[$1]=${KUGEL_DULL:index:1} ;;
  esac
}

_kugel_dull() {
  (( $3 > 0 && ($1 + 1) * $3 / $2 > $1 * $3 / $2 ))
}

# Draws jar VARIANT at sub-pixel X Y holding FILL marbles with OVERFLOW piled
# beside it, the pile clipped to MAX_COLUMNS; FAILED and FRESH as kugel_jar.
kugel_draw_jar() {
  local x0=$1 y0=$2 variant=$3 fill=$4 overflow=$5 limit=${6:-$KUGEL_CW} failed=${7:-0} fresh=${8:-0}
  local -n bg="KUGEL_JAR_${variant}_BG" ov="KUGEL_JAR_${variant}_OV"
  local -n slots="KUGEL_JAR_${variant}_SLOTS" spill="KUGEL_JAR_${variant}_SPILL"
  local -n jar_width="KUGEL_JAR_${variant}_JW" bead="KUGEL_JAR_${variant}_BEAD"
  local -n spill_bead="KUGEL_JAR_${variant}_SPILL_BEAD"
  local height=${#bg[@]} y x row c i shown beads dull total sx sy ss last=-1 bench_end
  local variant_name shade slot

  (( fill < 0 )) && fill=0
  (( fill > KUGEL_CAPACITY )) && fill=$KUGEL_CAPACITY
  (( overflow < 0 )) && overflow=0
  beads=$(( (fill * ${#slots[@]} + KUGEL_CAPACITY - 1) / KUGEL_CAPACITY ))
  KUGEL_JAR_BEADS=$beads

  shown=0
  for (( i = 0; i < overflow && i < ${#spill[@]}; i++ )); do
    slot=(${spill[i]})
    sx=${slot[0]}
    (( x0 + sx + spill_bead + 1 <= limit )) || break
    shown=$(( shown + 1 ))
    (( sx + spill_bead + 1 > last )) && last=$(( sx + spill_bead + 1 ))
  done
  KUGEL_SPILL_SHOWN=$shown
  bench_end=$(( jar_width - 1 ))
  (( last > bench_end )) && bench_end=$last
  (( x0 + bench_end >= limit )) && bench_end=$(( limit - x0 - 1 ))

  for (( y = 0; y < height; y++ )); do
    row=${bg[y]}
    for (( x = 0; x <= bench_end && x < ${#row}; x++ )); do
      c=${row:x:1}
      [ "$c" = . ] || kugel_put $(( x0 + x )) $(( y0 + y )) "$c"
    done
  done

  total=$(( fill + overflow ))
  dull=0
  (( total > 0 )) && dull=$(( (failed * beads + total / 2) / total ))
  for (( i = 0; i < beads; i++ )); do
    slot=(${slots[i]})
    sx=${slot[0]} sy=${slot[1]} ss=${slot[2]}
    variant_name=ruby
    _kugel_dull "$i" "$beads" "$dull" && variant_name=dull
    shade=$ss
    (( fresh == 1 && overflow == 0 && i == beads - 1 )) && { shade=-1; variant_name=ruby; }
    kugel_blit_marble $(( x0 + sx )) $(( y0 + sy )) "$bead" 0 "$variant_name" "$shade"
  done

  for (( y = 0; y < height; y++ )); do
    row=${ov[y]}
    for (( x = 0; x < jar_width && x < ${#row}; x++ )); do
      c=${row:x:1}
      [ "$c" = . ] && continue
      (( x0 + x < KUGEL_CW && y0 + y < KUGEL_CH )) || continue
      _kugel_lighten $(( (y0 + y) * KUGEL_CW + x0 + x )) "$c"
    done
  done

  dull=0
  (( total > 0 )) && dull=$(( (failed * shown + total / 2) / total ))
  for (( i = 0; i < shown; i++ )); do
    slot=(${spill[i]})
    sx=${slot[0]} sy=${slot[1]} ss=${slot[2]}
    variant_name=ruby
    _kugel_dull "$i" "$shown" "$dull" && variant_name=dull
    shade=$ss
    (( fresh == 1 && i == shown - 1 )) && { shade=-1; variant_name=ruby; }
    if (( sy + spill_bead == height - 1 )); then
      kugel_put $(( x0 + sx + 1 )) $(( y0 + height - 1 )) p
      kugel_put $(( x0 + sx + 2 )) $(( y0 + height - 1 )) p
    fi
    kugel_blit_marble $(( x0 + sx )) $(( y0 + sy )) "$spill_bead" 0 "$variant_name" "$shade"
  done
}

_kugel_sgr() {
  local key="$1|$2"
  if [ -z "${KUGEL_SGR[$key]:-}" ]; then
    if [ -n "$2" ]; then
      KUGEL_SGR[$key]="${SL_ESC}[0;38;2;${KUGEL_RGB[$1]};48;2;${KUGEL_RGB[$2]}m"
    else
      KUGEL_SGR[$key]="${SL_ESC}[0;38;2;${KUGEL_RGB[$1]}m"
    fi
  fi
  KUGEL_STYLE=${KUGEL_SGR[$key]}
}

# Packs KUGEL_PX into terminal rows: KUGEL_ROWS holds each row, already reset,
# with no trailing blanks, and KUGEL_WIDTHS its width in cells. A row that would
# start blank under NO_COLOR, or be empty, carries a zero-width space instead.
kugel_compose() {
  local row x last top bottom glyph line state top_index bottom_index width
  KUGEL_ROWS=()
  KUGEL_WIDTHS=()
  for (( row = 0; row * 2 < KUGEL_CH; row++ )); do
    top_index=$(( row * 2 * KUGEL_CW ))
    bottom_index=$(( top_index + KUGEL_CW ))
    last=-1
    for (( x = KUGEL_CW - 1; x >= 0; x-- )); do
      top=${KUGEL_PX[top_index + x]}
      bottom=${KUGEL_PX[bottom_index + x]:-.}
      if [ "$SL_USE_COLOR" != 1 ]; then
        case "$KUGEL_MONO_OFF" in *"$top"*) top=. ;; esac
        case "$KUGEL_MONO_OFF" in *"$bottom"*) bottom=. ;; esac
      fi
      [ "$top$bottom" = .. ] || { last=$x; break; }
    done
    line=''
    state=''
    for (( x = 0; x <= last; x++ )); do
      top=${KUGEL_PX[top_index + x]}
      bottom=${KUGEL_PX[bottom_index + x]:-.}
      if [ "$SL_USE_COLOR" != 1 ]; then
        case "$KUGEL_MONO_OFF" in *"$top"*) top=. ;; esac
        case "$KUGEL_MONO_OFF" in *"$bottom"*) bottom=. ;; esac
        case "$top$bottom" in
          ..) line+=' ' ;;
          ?.) line+='▀' ;;
          .?) line+='▄' ;;
          *) line+='█' ;;
        esac
        continue
      fi
      if [ "$top$bottom" = .. ]; then
        [ -n "$state" ] && { line+="${SL_ESC}[0m"; state=''; }
        line+=' '
        continue
      fi
      if [ "$bottom" = . ]; then
        glyph='▀'; _kugel_sgr "$top" ''
      elif [ "$top" = . ]; then
        glyph='▄'; _kugel_sgr "$bottom" ''
      elif [ "$top" = "$bottom" ]; then
        glyph='█'; _kugel_sgr "$top" ''
      else
        glyph='▀'; _kugel_sgr "$top" "$bottom"
      fi
      [ "$state" = "$KUGEL_STYLE" ] || { line+=$KUGEL_STYLE; state=$KUGEL_STYLE; }
      line+=$glyph
    done
    width=$(( last + 1 ))
    [ -n "$state" ] && line+="${SL_ESC}[0m"
    if [ "$last" -lt 0 ]; then
      line=$KUGEL_ZWSP
      width=1
    elif [ "$SL_USE_COLOR" != 1 ] && [ "${line:0:1}" = ' ' ]; then
      line=$KUGEL_ZWSP$line
      width=$(( width + 1 ))
    fi
    KUGEL_ROWS+=("$line")
    KUGEL_WIDTHS+=("$width")
  done
}

# Renders the jar on its own; see the header for the arguments.
kugel_jar() {
  local fill=${1:-0} overflow=${2:-0} variant=${3:-FULL} limit=${4:-${SL_COLUMNS:-80}}
  local failed=${5:-0} fresh=${6:-0}
  case "$fill$overflow$limit$failed$fresh" in *[!0-9]*) fill=0 overflow=0 limit=${SL_COLUMNS:-80} failed=0 fresh=0 ;; esac
  [ "$variant" = COMPACT ] || variant=FULL
  local -n width="KUGEL_JAR_${variant}_W" height="KUGEL_JAR_${variant}_H"
  local columns=$width
  (( columns > limit )) && columns=$limit
  kugel_canvas "$columns" "$height"
  kugel_draw_jar 0 0 "$variant" "$fill" "$overflow" "$limit" "$failed" "$fresh"
  kugel_compose
}

# Renders one marble on its own; see the header for the arguments.
kugel_marble() {
  local phase=${2:-0} rows
  _kugel_size "${1:-4}"
  rows=$(( (KUGEL_SIZE + 1) / 2 * 2 ))
  kugel_canvas $(( KUGEL_SIZE + 1 )) "$rows"
  kugel_blit_marble 0 $(( rows - KUGEL_SIZE )) "$KUGEL_SIZE" "$phase" "${3:-ruby}" "${4:-0}"
  kugel_compose
}
