"""The "meadow" theme: a cat in overgrown grass, under a sky that is the whole
terminal background.

Two halves, deliberately split:

  * The SKY is Windows Terminal's `backgroundImage` -- an animated pixel-cloud
    GIF generated by `meadowsky.py` and applied by `sl-water-bg.py apply-file`.
    The status line can only paint its own rows, so putting sky behind the whole
    window is the only way to get it behind your text as well.
  * This module paints only the FIELD: a short strip of overgrown grass with a
    cat walking through it, sitting on the last few rows above the info line.

The panel is therefore TRANSPARENT. No cell sets a background colour except the
soil, so the sky GIF shows through between the blades. That is the same trick
`water.overlay()` uses in its GIF mode, and for the same reason.

The cat is traced from a sprite sheet rather than drawn: see CAT_STAND. Its
colours are this theme's, not the sheet's.

Claude Code caps `refreshInterval` at one second, so this animates at ~1 fps
plus event-driven redraws. Everything moves slowly on purpose; at that sample
rate anything faster reads as teleporting.

THE DAY CYCLE lives in `daylight.py`: three looks -- day, sunset, night --
blended on a repeating loop, with the sky GIF and the terminal colour schemes
driven from the same clock so they cannot disagree. Nothing here holds a colour
constant any more; every draw call takes the palette for the current frame.

Sizing: SL_MEADOW_HEIGHT (a row count, or "full") overrides the default.
Time:   SL_MEADOW_PERIOD (seconds per cycle), SL_MEADOW_PHASE (pin the clock).
"""

