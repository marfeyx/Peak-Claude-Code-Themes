# --- motion -----------------------------------------------------------------
GRASS_SWAY = 0.30        # radians per second
CAT_SPEED = 1.4          # columns per second
CAT_STRIDE = 2.0         # columns per leg beat
SIT_STEP = 1.6           # seconds per idle pose
GROUND_ROWS = 1
INFO_ROWS = 1            # bottom rows the info text sits on, over the grass

# White text on grass is not safe by default: measured against the five daytime
# grass tones it runs 9.15 / 6.36 / 4.28 / 2.83 / 2.01 to 1, so the three
# brightest fail 4.5:1 outright. The info strip is therefore blended toward
# `pal["info_shade"]` before the text lands on it, which keeps the grass texture
# and colour visible while lifting the worst case to about 7:1.
#
# The mix has to RISE with the sunset, not stay fixed: sunset grass tips are
# (226, 178, 92), far brighter than any daytime tone, and at 0.50 white-on-gold
# comes out at 2.4:1. `info_mix` below re-derives the blend from the actual
# palette each frame instead of trusting one number for all three looks.
INFO_SHADE_MIX = 0.50
INFO_SHADE_MIX_MAX = 0.80
INFO_MIN_CONTRAST = 5.0

# Share of each traverse spent sitting at the far end rather than walking.
SIT_SHARE = 0.16

M64 = 0xFFFFFFFFFFFFFFFF


def noise(*key):
    """Deterministic hash in [0, 1). Keeps scenery stable between frames.

    Same splitmix64 finaliser the water theme uses, and for the same reason: a
    plain FNV over two small integers barely moves the low bits, so every
    threshold test lands on the same side and the field comes out in stripes.
    """
    h = 0x9E3779B97F4A7C15
    for k in key:
        h = (h + (int(k) & M64) + 0x9E3779B97F4A7C15) & M64
        h = ((h ^ (h >> 30)) * 0xBF58476D1CE4E5B9) & M64
        h = ((h ^ (h >> 27)) * 0x94D049BB133111EB) & M64
        h ^= h >> 31
    return (h & 0xFFFFFFFF) / 4294967296.0


HEIGHT_FILE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                           "statusline-meadow-height")


def height_setting():
    """SL_MEADOW_HEIGHT wins, then whatever was last stored on disk."""
    raw = os.environ.get("SL_MEADOW_HEIGHT", "").strip().lower()
    if raw:
        return raw
    try:
        with open(HEIGHT_FILE) as fh:
            return fh.read().strip().lower()
    except OSError:
        return ""


def panel_height(lines):
    """Rows of field.

    The sky is the terminal background now, so the panel only has to be tall
    enough to hold grass that buries a cat: the cat is 11 px, the grass wants to
    stand above it, and two pixels to a row makes that about nine rows. A taller
    panel just pushes your scrollback up for no scene.
    """
    raw = height_setting()
    if raw == "full":
        return max(6, lines - 4)
    if raw and raw != "auto":
        try:
            return max(4, min(int(raw), max(4, lines - 2)))
        except ValueError:
            pass
    # +1 on what the field alone needs: the info text is now the bottom row of
    # this panel rather than a separate row beneath it, so the total number of
    # terminal rows the status line occupies is unchanged.
    return max(8, min(lines - 11, 12))


# --- the field --------------------------------------------------------------

def blade_height(x, tall):
    """Pixel height of the grass blade rooted at column x.

    Squared rather than linear: most blades sit low and a few shoot well above
    the rest. A uniform distribution gives every column a middling height and
    the skyline comes out as noise with no silhouette to it.

    Was cubed, which pushed so many blades to the floor that the top half of the
    panel was bare and the field read as a thin strip along the bottom. Squaring
    keeps the tall-blade silhouette while actually filling the panel.
    """
    n = noise(x, 311)
    base = 2 + int((n ** 2) * (tall - 2)) if tall > 2 else tall
    return max(2, min(tall, base))


def mat_for(x, field_px):
    """Height of the solid part of the grass at column x.

    Varied per column, not constant. A flat mat with blades on top reads as a
    clipped hedge; letting the solid part rise and fall is what makes it a
    field. Kept in one place because `draw_flowers` has to reproduce it exactly
    or its blooms detach from their stems.

    The 0.34 is set against the cat, not chosen for looks: the cat is 11 px tall
    in an 18 px field, so a mat much above a third of the field swallows it
    whole. At this height the grass covers its legs and belly and leaves the
    back and head clear, which is what "in the grass" should look like.
    """
    return max(2, int(max(2, int(field_px * 0.34)) * (0.62 + 0.72 * noise(x, 21))))


def draw_field(canvas, px, width, height, t, pal):
    """Soil, then the background grass the cat walks in front of.

    Two passes per column. The lower one is a MAT -- filled straight up, no lean
    -- and the upper one is the leaning blade above it. One pass of leaning
    blades leaves gaps that flicker open and shut as the field sways, which at
    1 fps looks like the grass tearing rather than moving.
    """
    grass = pal["grass"]
    floor_y = height - GROUND_ROWS
    for y in range(floor_y, height):
        canvas.fill_row(y, pal["ground"])

    field_px = height * 2
    for x in range(width):
        sway = math.sin(t * GRASS_SWAY + noise(x, 7) * 6.283)
        mat = mat_for(x, field_px)
        h = max(mat + 1, blade_height(x, field_px))

        for j in range(h):                       # j = 0 at the root
            lean = j / float(max(1, field_px - 1))
            if j < mat:
                dx = 0                           # the mat does not move
            else:
                # Above the mat the lean scales with height, so the blade bends
                # instead of sliding sideways as a rigid column.
                over = (j - mat) / float(max(1, h - mat))
                dx = int(round(1.6 * over * over * sway))
            y = floor_y * 2 + 1 - j
            band = int(lean * len(grass))
            if j < mat:
                # Inside the mat `lean` is near zero, so every column resolved
                # to grass[0] and the bottom of the field came out as one flat
                # bar -- most visible on the info strip, which sits on it.
                # Hashing a band offset in breaks that into actual turf.
                band += int(noise(x, 401) * 2.4)
            shade = grass[min(len(grass) - 1, band)]
            px.set(x + dx, y, shade)
            # Blades taper: two pixels wide over the lower half of their free
            # length, one at the tip. Uniform one-pixel blades made the field
            # read as a barcode, every stroke the same weight.
            if j >= mat and (j - mat) < (h - mat) * 0.5:
                px.set(x + dx + 1, y, shade)


def draw_flowers(px, width, height, t, pal):
    """Blooms on the tips of some of the taller blades."""
    flowers = pal["flowers"]
    floor_y = height - GROUND_ROWS
    field_px = height * 2

    for x in range(width):
        if noise(x, 601) > 0.22:
            continue
        mat = mat_for(x, field_px)
        h = max(mat + 1, blade_height(x, field_px))
        if h < mat + 3:                 # too short to carry a head
            continue

        sway = math.sin(t * GRASS_SWAY + noise(x, 7) * 6.283)
        j = h - 1
        over = (j - mat) / float(max(1, h - mat))
        dx = int(round(1.6 * over * over * sway))
        y = floor_y * 2 + 1 - j
        which = int(noise(x, 77) * len(flowers)) % len(flowers)
        colour = flowers[which]

        # A three-pixel head with a contrasting centre. A single pixel was
        # invisible against the grass -- it just read as a lighter blade tip.
        px.set(x + dx, y - 1, colour)
        px.set(x + dx - 1, y - 1, colour)
        px.set(x + dx + 1, y - 1, colour)
        px.set(x + dx, y - 2, colour)
        # Index 1 is the buttercup, which is already the eye's colour; giving it
        # an eye would just flatten it. Compared by index rather than by value
        # because two blended flower colours can coincide mid-transition.
        px.set(x + dx, y, colour if which == 1 else pal["flower_eye"])


def draw_foreground_grass(px, width, height, t, pal):
    """A sparse layer drawn AFTER the cat, so it passes behind them.

    This is the only layer allowed to overwrite the cat. Without it the cat sits
    on the grass like a sticker; with it, it is in the field.
    """
    grass = pal["grass"]
    floor_y = height - GROUND_ROWS
    field_px = height * 2

    for x in range(width):
        if noise(x, 1201) > 0.18:
            continue
        # Hard-capped at nine pixels, which is the cat's shoulder. Front blades
        # therefore always cross its legs and body and never its face. Letting
        # them run to full height put a dark bar across the cat's head often
        # enough to matter, and at 1 fps it stays there for a whole second.
        top = max(4, min(int(field_px * 0.55), 9))
        h = max(3, min(top, 4 + int(noise(x, 1301) * (top - 4))))
        sway = math.sin(t * GRASS_SWAY * 1.3 + noise(x, 1401) * 6.283)
        for j in range(h):
            lean = j / float(max(1, h - 1))
            dx = int(round(1.8 * lean * lean * sway))
            y = floor_y * 2 + 1 - j
            # Nearer, so between the viewer and the light: darker.
            px.set(x + dx, y, lerp_rgb(grass[0], grass[3], lean * 0.7))


# --- fireflies ---------------------------------------------------------------
# Night needs something of its own, or it is only the day scene turned down. The
# flies are the one element that does not exist at all in the other two looks:
# they fade in with `daylight.nightness` rather than switching on, so they
# arrive with the colour instead of popping against a sunset.
#
# Each fly is a single pixel. Two is not an option -- at this scale a two-pixel
# glow is a bulb, not an insect -- so presence has to carry entirely on the
# blink, which is why the duty cycle below is short and the periods are hashed
# per fly rather than shared.
FIREFLIES = 14
FLY_PERIOD = (2.6, 6.4)          # seconds between blinks, per fly
FLY_DUTY = 0.26                  # share of that period spent lit


def draw_fireflies(px, width, height, t, pal, night):
    if night <= 0.02:
        return
    floor_y = height - GROUND_ROWS - INFO_ROWS
    field_px = floor_y * 2
    colour = pal["firefly"]

    for i in range(FIREFLIES):
        # Drift: a slow horizontal wander plus a slower vertical one, at rates
        # that do not divide into each other, so no two flies trace the same
        # path and none of them loops visibly.
        span = max(1, width - 2)
        x = int((noise(i, 91) * span
                 + 5.0 * math.sin(t * 0.13 + noise(i, 93) * 6.283)) % span)
        y = int(field_px * (0.22 + 0.52 * noise(i, 95))
                + 2.0 * math.sin(t * 0.09 + noise(i, 97) * 6.283))
        y = max(1, min(field_px - 1, y))

        period = FLY_PERIOD[0] + (FLY_PERIOD[1] - FLY_PERIOD[0]) * noise(i, 99)
        u = ((t + noise(i, 101) * period) % period) / period
        if u > FLY_DUTY:
            continue
        # Ease the blink in and out rather than flicking it: a hard on/off at
        # 1 fps reads as a dead pixel, a ramp reads as a pulse.
        glow = math.sin(math.pi * u / FLY_DUTY) * night
        px.set(x, floor_y * 2 + 1 - y,
               lerp_rgb(pal["grass"][0], colour, glow))


# --- the cat ----------------------------------------------------------------

def cat_pose(t, span):
    """(sprite, x, facing_right) for wall-clock time t.

    Position is a triangle wave over time rather than a counter, because every
    frame is a fresh process and nothing carries over. Each traverse ends with a
    pause in which the cat runs the sheet's sitting animation, then turns.

    The leg frame advances with DISTANCE, not with time, so the stride stays
    locked to the movement instead of drifting against it -- a cat whose legs
    cycle on their own clock moonwalks.
    """
    period = 2.0 * span / CAT_SPEED / max(0.05, 1.0 - 2 * SIT_SHARE)
    u = (t / period) % 1.0

    half = 0.5
    sit = SIT_SHARE * half            # sitting share of each half-traverse
    walk = half - sit

    leg = lambda d: CAT_WALK[int(d / CAT_STRIDE) % len(CAT_WALK)]
    seat = lambda: CAT_SIT[SIT_ORDER[int(t / SIT_STEP) % len(SIT_ORDER)]]

    if u < walk:                                   # walking right
        d = (u / walk) * span
        return leg(d), d, True
    if u < half:                                   # sitting at the right end
        return seat(), float(span), True
    if u < half + walk:                            # walking left
        d = ((u - half) / walk) * span
        return leg(d), span - d, False
    return seat(), 0.0, False                      # sitting at the left end


def draw_cat(px, width, height, t, pal):
    span = width - CAT_W
    if span <= 0:
        return
    sprite, x, rightward = cat_pose(t, span)

    # The cat stands one row higher than the grass floor, because the bottom
    # row now carries the info text. Without this the text lands across its
    # paws every time it walks past.
    floor_y = height - GROUND_ROWS - INFO_ROWS
    # Bottom-aligned: the sitting sprites are a row taller than the standing
    # one, and aligning by the top would make the cat sink when it sits.
    y0 = floor_y * 2 + 1 - len(sprite)
    px.blit(int(round(x)), y0, sprite, cat_palette(pal), flip=not rightward)


# --- assembly ---------------------------------------------------------------

def scene(width, height, t, pal=None, night=None):
    """Field only. Nothing paints a background except the soil, so the terminal
    background image -- the sky -- shows through everywhere else.

    `pal` defaults to the palette for the current phase; passing one explicitly
    is how the preview renderer walks the cycle without waiting for it.
    """
    if pal is None:
        pal = daylight.palette_now(t)
    if night is None:
        night = daylight.nightness()

    canvas = Canvas(width, height)
    px = Pixels(width, height)

    draw_field(canvas, px, width, height, t, pal)
    draw_flowers(px, width, height, t, pal)
    draw_fireflies(px, width, height, t, pal, night)
    draw_cat(px, width, height, t, pal)
    draw_foreground_grass(px, width, height, t, pal)
    px.flush(canvas)
    return canvas


def plain(width, height, night=0.0):
    """No-truecolor fallback: the shape of the field, in 256 colours."""
    # Three 256-colour stand-ins for the three looks. Nothing is blended here --
    # the cube has nowhere near the resolution for it, and a fallback that
    # cannot show the sky has little to gain from a gradual field.
    if night > 0.6:
        soil, blade = 236, 23
    elif night > 0.15:
        soil, blade = 95, 137
    else:
        soil, blade = 94, 71
    rows = []
    for y in range(height):
        rows.append(c(soil, "▄" * width) if y >= height - GROUND_ROWS
                    else c(blade, "\"" * width))
    return rows


SEP = "  ·  "


def char_cols(ch):
    """Terminal columns one character occupies: 1 or 2.

    Never 0, because `clean` has already removed combining marks -- a Canvas
    cell holds exactly one character, so there is nowhere to put a zero-width
    mark and no way to represent it without desynchronising cells from columns.
    """
    return 2 if unicodedata.east_asian_width(ch) in ("W", "F") else 1


def text_cols(s):
    return sum(char_cols(ch) for ch in s)


def clean(value, limit=160):
    """Coerce a payload field to a safe, printable, single-line string.

    Three separate hazards, all of them reachable from ordinary data:

      * Control characters. A newline in a branch name or a directory name is
        written straight into a canvas cell and splits the status line into an
        extra terminal row; a raw ESC would let the payload emit its own colour
        sequences. Anything below 0x20 plus DEL is dropped.
      * Wrong types. Claude Code's payload is not schema-checked here, and a
        non-string where a string is expected used to raise and collapse the
        whole panel into a single over-wide error line.
      * Unbounded length. Capped so one pathological field cannot dominate the
        fitter.
    """
    if value is None:
        return ""
    if not isinstance(value, str):
        value = str(value)
    # NFC first so accented text composes into single code points, then drop
    # whatever combining marks remain: a cell holds one character, so a mark
    # that is meant to stack on its neighbour has nowhere to go.
    value = unicodedata.normalize("NFC", value)
    out = "".join(ch for ch in value
                  if ch >= " " and ch != "\x7f" and not unicodedata.combining(ch))
    return out[:limit]


def info_segments(d, pct, width=None):
    """Fitted [(text, colour256)], lowest priority dropped first.

    Same fitting the water theme uses, and for the same reason -- branch and
    model names are unbounded, and an unbudgeted row wraps onto a second line,
    which changes the panel height as those strings change length.

    The budget is spent in TERMINAL COLUMNS, not characters. `len()` counts
    code points, but a CJK or emoji code point occupies two columns, so a row
    that is exactly `cols` characters long renders wider than `cols` columns --
    measured at COLUMNS=80 with a CJK path and branch, the row came out 95
    columns wide. The other themes absorb that in their two-column reserve;
    this one is full-bleed and has no slack to absorb it with.
    """
    seg = [(f"ctx {pct:.0f}%", DIM, 6)]

    # Subagent progress, when a fan-out is in flight. Priority 5 -- above
    # everything except the context gauge -- because it is the only segment
    # here that is transient: the path and the model will still be there next
    # frame, and a count of running agents is the thing you are watching for.
    # `agentcount` returns "" whenever nothing is running, so the row is
    # unchanged in the ordinary case.
    agents = clean(agentcount.label(d), 24)
    if agents:
        seg.append((agents, 222, 5))

    cwd = clean(dig(d, "workspace", "current_dir") or d.get("cwd") or "") or os.getcwd()
    seg.append((clean(short_path(cwd, 34)), 80, 3))

    branch = clean(dig(d, "worktree", "branch") or git_branch(cwd) or "")
    if branch:
        seg.append((branch, 252, 2))

    model = clean(dig(d, "model", "display_name") or dig(d, "model", "id") or "")
    if model:
        seg.append((model, 110, 1))

    cost = dig(d, "cost", "total_cost_usd")
    if cost is not None:
        try:
            seg.append((money(float(cost)), 215, 0))
        except (TypeError, ValueError):
            pass

    if width is not None:
        sep_cols = text_cols(SEP)

        def visible(items):
            return (sum(text_cols(s) for s, _, _ in items)
                    + sep_cols * max(0, len(items) - 1))

        while len(seg) > 1 and visible(seg) > width:
            seg.pop(min(range(len(seg)), key=lambda i: seg[i][2]))
        if seg and visible(seg) > width:          # one segment, still too wide
            text, colour, pri = seg[0]
            # Truncate by COLUMNS as well, or a wide-character segment still
            # overflows after the ellipsis is added.
            budget, kept = max(1, width - 1), []
            used = 0
            for ch in text:
                w = char_cols(ch)
                if used + w > budget:
                    break
                kept.append(ch)
                used += w
            seg = [("".join(kept) + "…", colour, pri)]

    return [(text, colour) for text, colour, _ in seg]


def info_row(d, pct, width=None):
    """ANSI one-liner. Only the no-truecolor fallback uses this now."""
    return c(DIM, SEP).join(c(colour, text)
                            for text, colour in info_segments(d, pct, width))


def relative_luminance(colour):
    """WCAG relative luminance, for the contrast check below."""
    chans = []
    for v in colour:
        v /= 255.0
        chans.append(v / 12.92 if v <= 0.03928
                     else ((v + 0.055) / 1.055) ** 2.4)
    return 0.2126 * chans[0] + 0.7152 * chans[1] + 0.0722 * chans[2]


def contrast(a, b):
    la, lb = relative_luminance(a), relative_luminance(b)
    if la < lb:
        la, lb = lb, la
    return (la + 0.05) / (lb + 0.05)


def info_mix(pal):
    """How far to blend the info strip toward `info_shade` this frame.

    Solved rather than fixed. The strip has to clear INFO_MIN_CONTRAST against
    the brightest thing that can sit under the text -- the top grass band, which
    at sunset is a bright gold -- and the cheapest honest way to guarantee that
    across a continuum of palettes is to raise the blend until it does. Ten
    steps is enough: the contrast curve is monotonic in the mix, so the answer
    is the first step that passes.
    """
    text, shade, bright = pal["info_text"], pal["info_shade"], pal["grass"][-1]
    for i in range(11):
        mix = INFO_SHADE_MIX + (INFO_SHADE_MIX_MAX - INFO_SHADE_MIX) * i / 10.0
        if contrast(text, lerp_rgb(bright, shade, mix)) >= INFO_MIN_CONTRAST:
            return mix
    return INFO_SHADE_MIX_MAX


def draw_info(canvas, d, pct, pal):
    """Paint the info text onto the bottom row, over the grass.

    The text used to be a separate row below the panel, sitting on the
    terminal's own background, which left a bare strip under the field. Drawing
    it into the canvas is what lets the grass run all the way to the bottom
    edge.

    The strip is darkened first (see `info_mix`): `Canvas.put` leaves a cell's
    background alone when passed bg=None, so the shading has to happen as a
    separate pass before the glyphs land, or the text would sit on raw grass and
    fail contrast on the three brightest tones.
    """
    y = canvas.height - 1
    parts = info_segments(d, pct, canvas.width - 2)
    if not parts:
        return
    shade, mix = pal["info_shade"], info_mix(pal)

    # Shade ONLY the run the text actually covers, plus a cell of margin. The
    # first version darkened the whole row, which turned the bottom of the
    # field into a flat bar the width of the terminal -- the grass was still
    # there, it had just been flattened into a band. Everything past the end of
    # the text is now left as turf.
    plain_text = SEP.join(text for text, _ in parts)
    start = 1
    # Cells, not characters. A wide glyph occupies one cell but two columns, so
    # the shaded run is sized from the cell count the writer will actually use.
    span = sum(1 for _ in plain_text)
    for x in range(max(0, start - 1), min(canvas.width, start + span + 1)):
        ch, fg, bg = canvas.cells[y][x]
        canvas.cells[y][x] = [
            ch,
            lerp_rgb(fg, shade, mix) if fg else fg,
            lerp_rgb(bg if bg else pal["ground"], shade, mix),
        ]

    def write(x, s, fg):
        """Write `s` from cell x, keeping cells and columns in step.

        A double-width glyph is painted into one cell and followed by a cell
        holding the empty string. `Canvas.rows()` appends each cell's character
        verbatim, so an empty one emits no byte at all -- which is exactly what
        a wide glyph's second column needs, since the terminal has already
        advanced the cursor two columns for it. Writing a space there instead
        would add a third column and push the row over the terminal width.
        """
        for ch in s:
            if x >= canvas.width:
                break
            canvas.put(x, y, ch, fg)
            x += 1
            if char_cols(ch) == 2 and x < canvas.width:
                canvas.put(x, y, "", fg)
                x += 1
        return x

    x = start
    for i, (text, _) in enumerate(parts):
        if i:
            x = write(x, SEP, pal["info_sep"])
        x = write(x, text, pal["info_text"])


def render(d):
    cols, lines = term_size()
    # The field runs FULL BLEED: every column of the terminal, no reserve.
    #
    # The other themes hold back STATUSLINE_RULE_PAD columns so a rule or a text
    # row cannot overflow and wrap. A field is not text -- holding two columns
    # back leaves a strip of bare terminal down the right edge, and against an
    # edge-to-edge sky that gap is the first thing you see. Claude Code renders
    # status rows with wrap:"truncate", so the failure mode if this is ever one
    # column too wide is a clipped last column, not a wrapped extra row.
    # SL_MEADOW_BLEED=0 puts the reserve back.
    bleed = os.environ.get("SL_MEADOW_BLEED", "1") != "0"
    pad = 0 if bleed else env_int("STATUSLINE_RULE_PAD", 2)
    width = max(20, cols - pad)
    # The info row IS text, so it keeps the reserve regardless.
    text_width = max(20, cols - env_int("STATUSLINE_RULE_PAD", 2))

    # float() on a string, list or dict raises, and a raise here collapses the
    # whole 12-row panel into a single over-wide "theme failed" line. Nothing
    # validates the payload's types before it reaches us.
    try:
        pct = max(0.0, min(100.0, float(dig(d, "context_window", "used_percentage"))))
    except (TypeError, ValueError):
        pct = 0.0

    now = time.time()
    p = daylight.phase(now)
    pal = daylight.palette(p)
    night = daylight.nightness(p)

    # The sky and the two colour schemes are not ours to paint -- they live in
    # Windows Terminal's profile and in Claude Code's settings. Nudging them
    # along the same clock is a file write on a drvfs mount, far too slow to sit
    # in a frame, so it is handed to a detached process that this call does not
    # wait on. It is a no-op unless the phase has actually crossed a boundary.
    try:
        import skydriver
        skydriver.tick(p)
    except Exception:
        pass

    height = panel_height(lines)
    if not truecolor():
        return (plain(width, height - INFO_ROWS, night)
                + [info_row(d, pct, text_width)])

    canvas = scene(width, height, now, pal, night)
    draw_info(canvas, d, pct, pal)
    return canvas.rows()
